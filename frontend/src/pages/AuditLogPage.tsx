import React, { useState, useEffect } from 'react';
import { taskApi } from '../services/api';
import { Task, TaskActivityLog } from '../types';
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from '../components/ui/Card';
import { ActivityTimeline } from '../components/task/ActivityTimeline';
import { History, Search, ShieldCheck } from 'lucide-react';

export const AuditLogPage: React.FC = () => {
  const [allLogs, setAllLogs] = useState<TaskActivityLog[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchGlobalAuditLogs = async () => {
      setLoading(true);
      try {
        const res = await taskApi.getTasks();
        const aggregatedLogs: TaskActivityLog[] = [];
        res.tasks?.forEach((t: any) => {
          if (t.activityLogs) {
            aggregatedLogs.push(...t.activityLogs);
          }
        });
        // Sort by timestamp desc
        aggregatedLogs.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
        setAllLogs(aggregatedLogs);
      } catch (err) {
        console.error('Failed to fetch audit logs:', err);
      } finally {
        setLoading(false);
      }
    };
    fetchGlobalAuditLogs();
  }, []);

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-2xl font-extrabold text-slate-100 tracking-tight">Process Audit Traceability Trail</h2>
        <p className="text-sm text-slate-400">Immutable logging of who performed what state change, when, and why across all workflows.</p>
      </div>

      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <History className="w-5 h-5 text-indigo-400" /> Organizational Activity Log History
          </CardTitle>
          <CardDescription>
            Chronological audit logs generated by task execution, stage transitions, and approval actions.
          </CardDescription>
        </CardHeader>
        <CardContent>
          {loading ? (
            <div className="py-12 text-center text-slate-400 flex items-center justify-center space-x-2">
              <div className="w-5 h-5 border-2 border-indigo-500 border-t-transparent rounded-full animate-spin" />
              <span>Fetching audit trail records...</span>
            </div>
          ) : allLogs.length === 0 ? (
            <div className="py-12 text-center text-slate-400">
              <ShieldCheck className="w-12 h-12 text-indigo-400 mx-auto mb-3" />
              <h3 className="font-bold text-slate-200 text-lg">No Audit Logs Captured Yet</h3>
              <p className="text-xs text-slate-500 mt-1">Audit log records are generated automatically upon task actions.</p>
            </div>
          ) : (
            <div className="pt-2">
              <ActivityTimeline logs={allLogs} />
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
};
