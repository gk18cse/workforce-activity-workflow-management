import React, { useState, useEffect } from 'react';
import { taskApi } from '../services/api';
import { TaskActivityLog } from '../types';
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from '../components/ui/Card';
import { ActivityTimeline } from '../components/task/ActivityTimeline';
import { History, ShieldCheck } from 'lucide-react';

export const AuditLogPage: React.FC = () => {
  const [allLogs, setAllLogs] = useState<TaskActivityLog[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchGlobalAuditLogs = async () => {
      setLoading(true);
      try {
        const res = await taskApi.getTasks();
        const aggregatedLogs: TaskActivityLog[] = [];
        res.tasks?.forEach((t: any) => {
          if (t.activityLogs) {
            aggregatedLogs.push(...t.activityLogs);
          }
        });
        // Sort by timestamp desc
        aggregatedLogs.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
        setAllLogs(aggregatedLogs);
      } catch (err) {
        console.error('Failed to fetch audit logs:', err);
      } finally {
        setLoading(false);
      }
    };
    fetchGlobalAuditLogs();
  }, []);

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-2xl sm:text-3xl font-sratome font-bold tracking-wider uppercase text-foreground">
          Process Audit Traceability Trail
        </h2>
        <p className="text-xs text-muted-foreground font-sans mt-0.5">
          Immutable logging of who performed what state change, when, and why across all workflows.
        </p>
      </div>

      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <History className="w-4 h-4 text-muted-foreground" /> Organizational Activity Log History
          </CardTitle>
          <CardDescription className="font-sans">
            Chronological audit logs generated by task execution, stage transitions, and approval actions.
          </CardDescription>
        </CardHeader>
        <CardContent>
          {loading ? (
            <div className="py-12 text-center text-muted-foreground flex items-center justify-center space-x-2 font-sratome text-xs">
              <div className="w-4 h-4 border-2 border-primary border-t-transparent rounded-full animate-spin" />
              <span>Fetching audit trail records...</span>
            </div>
          ) : allLogs.length === 0 ? (
            <div className="py-12 text-center text-muted-foreground">
              <ShieldCheck className="w-10 h-10 text-muted-foreground mx-auto mb-2" />
              <h3 className="font-sratome font-bold uppercase tracking-wider text-foreground text-sm">No Audit Logs Captured Yet</h3>
              <p className="text-xs text-muted-foreground mt-1 font-sans">Audit log records are generated automatically upon task actions.</p>
            </div>
          ) : (
            <div className="pt-2">
              <ActivityTimeline logs={allLogs} />
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
};
